import ast
import sqlite3
import unittest
from datetime import date, datetime
from pathlib import Path

class SemesterInvoiceTests(unittest.TestCase):
    def setUp(self):
        self.db = sqlite3.connect(':memory:')
        self.db.executescript('''
        CREATE TABLE enrollments(id INTEGER PRIMARY KEY,student_name,course_type_name,final_price,package_amount,package_lessons,auto_renew_lessons);
        INSERT INTO enrollments VALUES(284,'Student','Private Lesson',82.5,825,10,10);
        CREATE TABLE invoices(id INTEGER PRIMARY KEY,student_name,schedule_id,charge_lessons,amount,status,invoice_type,created_at,enrollment_id,due_date,notes,credits_applied,coverage_start);
        INSERT INTO invoices VALUES(242,'Student',NULL,10,825,'unpaid','initial_tuition','2026-11-03',284,'2026-11-03','Tuition invoice manually generated by owner.',0,NULL);
        CREATE TABLE wallet(balance); INSERT INTO wallet VALUES(-10);
        ''')
        src = Path(__file__).with_name('app.py').read_text()
        node = next(n for n in ast.parse(src).body if isinstance(n,ast.FunctionDef) and n.name=='create_enrollment_invoice')
        ns = dict(date=date,datetime=datetime,hmusic_attach_pending_invoice_charges=lambda *a:None)
        exec(compile(ast.Module(body=[node],type_ignores=[]),'app.py','exec'),ns)
        self.create = ns['create_enrollment_invoice']
    def tearDown(self):
        self.db.close()
    def call(self, semester=''):
        return self.create(self.db.cursor(),284,'initial_tuition','Tuition invoice manually generated by owner.',semester_start=semester)
    def test_existing_unpaid_is_reused(self):
        self.assertEqual(self.call(),242)
    def test_new_semester_keeps_old_debt_and_credits(self):
        iid=self.call('2026-11-09')
        self.assertNotEqual(iid,242)
        self.assertEqual(self.db.execute('SELECT amount,status FROM invoices WHERE id=242').fetchone(),(825,'unpaid'))
        self.assertEqual(self.db.execute('SELECT balance FROM wallet').fetchone()[0],-10)
        self.assertEqual(self.db.execute('SELECT credits_applied,coverage_start FROM invoices WHERE id=?',(iid,)).fetchone(),(0,'2026-11-09'))
        self.assertEqual(self.db.execute('SELECT charge_lessons,amount,status FROM invoices WHERE id=?',(iid,)).fetchone(),(10,825,'unpaid'))
    def test_repeated_submission_and_paid_semester_do_not_duplicate(self):
        iid=self.call('2026-11-09')
        self.assertEqual(self.call('2026-11-09'),iid)
        self.db.execute("UPDATE invoices SET status='paid' WHERE id=?",(iid,))
        self.assertEqual(self.call('2026-11-09'),iid)
        self.assertEqual(self.db.execute('SELECT count(*) FROM invoices').fetchone()[0],2)
    def test_different_semester_is_independent(self):
        self.assertNotEqual(self.call('2026-11-09'),self.call('2027-01-11'))
    def test_invalid_date_does_not_create(self):
        for v in ('not-date','2026-02-30','20261109'):
            with self.assertRaises(ValueError):self.call(v)
        self.assertEqual(self.db.execute('SELECT count(*) FROM invoices').fetchone()[0],1)

if __name__=='__main__':unittest.main()
